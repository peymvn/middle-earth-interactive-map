"""Build web/data/relief.js: a coarse "local base elevation" grid used to tell mountains from
high plateaus.

Absolute height is a poor mountain test in Middle-earth: Mordor's plain lies at ~1,200 m while the
Ephel Dúath above it reach only ~2,000 m, and Rohan sits at ~600 m below the White Mountains. The
renderer therefore colours rock, grey mountain tints and snow by *relief*: height above the low
ground around a point. This file holds that low ground (a minimum filter over ~25 km, smoothed) on
a 512 x 512 grid (~3.9 km cells), as deflated Int16 metres in base64.

Run after build_terrain.py (needs build_tmp/E6.npy):  .venv/bin/python tools/build_relief.py
"""
import base64
import os
import sys
import zlib

import numpy as np
from scipy import ndimage

sys.path.insert(0, os.path.dirname(__file__))
from common import MAXZ  # noqa

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
N = 512


def main():
    E = np.load(os.path.join(ROOT, 'build_tmp', f'E{MAXZ}.npy'), mmap_mode='r')
    k = E.shape[0] // N
    g = np.empty((N, N), np.float32)
    for r in range(N):
        rows = np.asarray(E[r * k:(r + 1) * k], np.float32) / 2
        g[r] = np.maximum(rows, 0).reshape(k, N, k).mean(axis=(0, 2))
    base = ndimage.minimum_filter(g, size=7)          # ~27 km window
    base = ndimage.gaussian_filter(base, 3)
    base = np.minimum(base, g)                         # never above the ground itself
    raw = np.round(base).astype('<i2').tobytes()
    b64 = base64.b64encode(zlib.compress(raw, 9)).decode()
    out = os.path.join(ROOT, 'web', 'data', 'relief.js')
    with open(out, 'w') as f:
        f.write('// Generated by tools/build_relief.py: local base elevation (m), 512x512 Int16, deflate+base64.\n')
        f.write(f'window.ME_RELIEF = {{ n: {N}, b64: "{b64}" }};\n')
    print('wrote', out, os.path.getsize(out) // 1024, 'KB', 'relief max', float((g - base).max()))


if __name__ == '__main__':
    main()
