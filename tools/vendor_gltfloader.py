"""Fetch three.js r160's GLTFLoader (an ES module) and write a plain-script build that uses the global
THREE, so the map keeps working from file:// without a bundler. Output: web/vendor/three/GLTFLoader.global.js
"""
import re, urllib.request, os
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
BASE = 'https://unpkg.com/three@0.160.0/examples/jsm/'

def get(path):
    return urllib.request.urlopen(BASE + path).read().decode()

def strip(src, module_names):
    names = []
    def imp(m):
        names.extend(n.strip().split(' as ')[0].strip() for n in m.group(1).split(',') if n.strip())
        return ''
    src = re.sub(r"import\s*\{([^}]*)\}\s*from\s*'[^']*';", imp, src)
    return src, names

out = ["// Generated by tools/vendor_gltfloader.py from three.js r160 (MIT). Do not edit.", "(function () {", "'use strict';"]
utils, names_u = strip(get('utils/BufferGeometryUtils.js'), [])
utils = re.sub(r'^export\s+', '', utils, flags=re.M)
utils = re.sub(r'^\{[^}]*\};?\s*$', '', utils, flags=re.M)
loader, names_l = strip(get('loaders/GLTFLoader.js'), [])
loader = re.sub(r'^export\s*\{[^}]*\};?\s*$', '', loader, flags=re.M)
three_names = sorted(set(n for n in names_u + names_l if n not in ('toTrianglesDrawMode',)))
out.append('const { ' + ', '.join(three_names) + ' } = THREE;')
out.append(utils)
out.append(loader)
out.append('THREE.GLTFLoader = GLTFLoader;')
out.append('})();')
dst = os.path.join(ROOT, 'web', 'vendor', 'three', 'GLTFLoader.global.js')
open(dst, 'w').write('\n'.join(out))
print('wrote', dst, os.path.getsize(dst) // 1024, 'KB')
